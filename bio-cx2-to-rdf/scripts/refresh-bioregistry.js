#!/usr/bin/env node
/**
 * Refresh the vendored Bioregistry canonical-prefix map.
 *
 * Build-time tool: queries Bioregistry for each prefix and (re)writes
 * src/core/bioregistry-prefixes.ts. Only prefixes that expose an `rdf_uri_format`
 * (a proper RDF identity IRI, e.g. uniprot, chebi) are canonicalized; prefixes
 * whose canonical is merely a provider webpage (no rdf_uri_format, e.g. cas,
 * hgnc.symbol) are left to the network's own @context at conversion time.
 *
 * Querying at build time keeps conversion deterministic and offline. A future,
 * more general cx2->RDF tool may instead resolve prefixes against the live
 * Bioregistry API during conversion (with caching) — see CX2_TO_RDF_DESIGN.md.
 *
 * Usage:
 *   node scripts/refresh-bioregistry.js [prefix ...]
 *   npm run refresh:bioregistry
 * With no args, refreshes the prefixes seen in NCI-PID @context blocks.
 */
import { get } from 'node:https';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const DEFAULT_PREFIXES = ['uniprot', 'chebi', 'cas', 'hgnc.symbol', 'hprd', 'kegg.compound'];

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    get(url, (res) => {
      let body = '';
      res.on('data', (chunk) => (body += chunk));
      res.on('end', () => {
        try {
          resolve(JSON.parse(body));
        } catch (err) {
          reject(err);
        }
      });
    }).on('error', reject);
  });
}

/** A usable IRI stem requires the identifier placeholder at the very end. */
function toStem(format) {
  return format && format.endsWith('$1') ? format.slice(0, -2) : null;
}

async function main() {
  const args = process.argv.slice(2);
  const prefixes = args.length > 0 ? args : DEFAULT_PREFIXES;
  const map = {};

  for (const prefix of prefixes) {
    try {
      const data = await fetchJson(
        `https://bioregistry.io/api/registry/${encodeURIComponent(prefix)}`
      );
      const stem = toStem(data.rdf_uri_format);
      if (stem) {
        map[prefix] = stem;
        console.error(`  ${prefix} -> ${stem}`);
      } else {
        console.error(`  ${prefix}: no rdf_uri_format — left to @context`);
      }
    } catch (err) {
      console.error(`  ${prefix}: query failed (${err.message})`);
    }
  }

  const here = dirname(fileURLToPath(import.meta.url));
  const outPath = join(here, '..', 'src', 'core', 'bioregistry-prefixes.ts');
  const content = `/**
 * Canonical IRI stems keyed by CURIE prefix, vendored from Bioregistry
 * (\`rdf_uri_format\`). Used to canonicalize a network's @context prefixes.
 *
 * AUTO-GENERATED by scripts/refresh-bioregistry.js — do not edit by hand.
 * Regenerate with: npm run refresh:bioregistry
 * Fetched: ${new Date().toISOString().slice(0, 10)}
 *
 * A build-time snapshot keeps conversion deterministic and offline. A future
 * general cx2->RDF tool may resolve unknown prefixes against the live Bioregistry
 * API during conversion (with caching); see CX2_TO_RDF_DESIGN.md.
 */
export const BIOREGISTRY_PREFIXES: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;
  await writeFile(outPath, content, 'utf-8');
  console.error(`Wrote ${Object.keys(map).length} canonical prefix(es) to ${outPath}`);
}

main();
